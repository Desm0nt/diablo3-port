#!/usr/bin/env python3
# Diablo III: Challenge Rift data for the offline Challenge Rift mod (dm/host/hle_d3_mods.c, DM_D3_CHALLENGE).
# Turns d3hack's weekly dumps (examples/config/d3hack-nx/rift_data: challengerift_config.dat = D3.ChallengeRifts.ChallengeData,
# challengerift_NN.dat = D3.Leaderboard.WeeklyChallengeData, the files Blizzard's servers sent to the game) into
# dm/host/hle_d3_rift_data.inc, which is compiled into libdm. Every weekly file must have the three top-level messages the game
# asks for (rift_snapshot 1, hero_snapshot 2, account_snapshot 3) or it is refused here.
#   python tools/d3_rift_inc.py <d3hack checkout>/examples/config/d3hack-nx/rift_data
import glob, hashlib, os, sys

def varint(b, i):
    v = s = 0
    while True:
        c = b[i]; i += 1; v |= (c & 0x7f) << s; s += 7
        if not c & 0x80: return v, i

def top_fields(b):
    i = 0; seen = {}
    while i < len(b):
        t, i = varint(b, i); f, w = t >> 3, t & 7
        if w == 0: v, i = varint(b, i); seen[f] = v
        elif w == 1: i += 8
        elif w == 5: i += 4
        elif w == 2: n, i = varint(b, i); seen[f] = n; i += n
        else: raise ValueError('wire type %d' % w)
    if i != len(b): raise ValueError('truncated')
    return seen

def arr(name, b):
    out = ['static const uint8_t %s[%d] = {' % (name, len(b))]
    for i in range(0, len(b), 40): out.append(','.join(str(x) for x in b[i:i + 40]) + ',')
    out.append('};')
    return out

def main():
    src = sys.argv[1]
    cfg = open(os.path.join(src, 'challengerift_config.dat'), 'rb').read()
    cf = top_fields(cfg)
    if 1 not in cf or 5 not in cf: sys.exit('challengerift_config.dat: no challenge_number / challenge_hash')
    files = sorted(glob.glob(os.path.join(src, 'challengerift_[0-9][0-9].dat')))
    h = hashlib.sha256(cfg)
    lines = ['// Generated by tools/d3_rift_inc.py from d3hack (https://github.com/god-jester/d3hack, c0f0dbd) examples/config/d3hack-nx/rift_data:',
             '// challengerift_config.dat and %d weekly Challenge Rift files as Blizzard\'s servers sent them to the game. Do not edit.' % len(files)]
    body = arr('k_rift_cfg', cfg); names = []
    for n, p in enumerate(files):
        b = open(p, 'rb').read(); f = top_fields(b)
        if os.path.basename(p) != 'challengerift_%02d.dat' % n: sys.exit('%s: files must be numbered without gaps' % p)
        if not (1 in f and 2 in f and 3 in f): sys.exit('%s: rift / hero / account snapshot missing' % p)
        h.update(b); body += arr('k_rift_%02d' % n, b); names.append('{k_rift_%02d, %d}' % (n, len(b)))
    lines.append('// SHA-256 of the config followed by the weekly files in order: %s' % h.hexdigest())
    lines += body
    lines.append('static const struct { const uint8_t *p; uint32_t n; } k_rifts[%d] = {' % len(files))
    for i in range(0, len(names), 6): lines.append('    ' + ', '.join(names[i:i + 6]) + ',')
    lines.append('};')
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dm', 'host', 'hle_d3_rift_data.inc')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('%s: config %d bytes, %d weekly files, %d bytes' % (os.path.normpath(out), len(cfg), len(files), sum(os.path.getsize(p) for p in files)))

main()
